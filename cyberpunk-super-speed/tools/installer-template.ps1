# ---------------------------------------------------------------------------
# Everything below is PowerShell. The lines above only start it.
#
# What this does:
#   1. Finds your Steam copy of Cyberpunk 2077 (or asks you where it is).
#   2. If RED4ext or Cyber Engine Tweaks are missing, asks before downloading
#      them from their official GitHub release pages into the game folder.
#   3. Writes the Super Speed mod into
#      Cyberpunk 2077\bin\x64\plugins\cyber_engine_tweaks\mods\SuperSpeed\init.lua
#
# Generated by tools/build_installer.py from tools/installer-template.ps1 and
# the mod's init.lua. Edit those, not the .bat.
# ---------------------------------------------------------------------------

$ErrorActionPreference = 'Stop'
$ProgressPreference = 'SilentlyContinue'
[Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12

function Say([string]$text, [string]$color = 'Gray') {
    Write-Host $text -ForegroundColor $color
}

# Plain path joining. (Join-Path errors on drives that don't exist, such as an
# unplugged drive that still has a Steam library listed.)
function Combine([string]$a, [string]$b) {
    return [IO.Path]::Combine($a, $b)
}

function Is-GameFolder([string]$dir) {
    try { return Test-Path -LiteralPath (Combine $dir 'bin\x64\Cyberpunk2077.exe') } catch { return $false }
}

function Find-Game {
    $roots = New-Object System.Collections.Generic.List[string]
    $steam = $null
    try { $steam = (Get-ItemProperty -Path 'HKCU:\Software\Valve\Steam' -ErrorAction Stop).SteamPath } catch { }
    if ($steam) {
        $steam = $steam -replace '/', '\'
        $roots.Add($steam)
        # Games can live in other Steam library folders (e.g. on another drive).
        $vdf = Combine $steam 'steamapps\libraryfolders.vdf'
        if (Test-Path -LiteralPath $vdf) {
            foreach ($line in Get-Content -LiteralPath $vdf) {
                if ($line -match '"path"\s+"([^"]+)"') {
                    $roots.Add(($Matches[1] -replace '\\\\', '\'))
                }
            }
        }
    }
    $roots.Add("${env:ProgramFiles(x86)}\Steam")

    foreach ($root in $roots) {
        $dir = Combine $root 'steamapps\common\Cyberpunk 2077'
        if (Is-GameFolder $dir) { return $dir }
    }
    return $null
}

function Ask-ForGame {
    while ($true) {
        Say ''
        Say "I couldn't find Cyberpunk 2077 automatically." 'Yellow'
        Say 'In Steam: right-click Cyberpunk 2077 > Manage > Browse local files.'
        Say 'Copy the folder path from the top of that window and paste it here.'
        $answer = Read-Host 'Game folder (or press Enter to quit)'
        $answer = $answer.Trim().Trim('"')
        if (-not $answer) { return $null }
        if (Is-GameFolder $answer) { return $answer }
        Say "That folder doesn't contain bin\x64\Cyberpunk2077.exe. Try again." 'Red'
    }
}

function Install-FromGitHub([string]$repo, [string]$assetPattern, [string]$label, [string]$gameDir) {
    Say "Downloading $label..."
    $headers = @{ 'User-Agent' = 'SuperSpeed-installer' }
    $release = Invoke-RestMethod -Uri "https://api.github.com/repos/$repo/releases/latest" -Headers $headers -UseBasicParsing
    $asset = $release.assets | Where-Object { $_.name -match $assetPattern } | Select-Object -First 1
    if (-not $asset) { throw "Couldn't find a download for $label on its release page." }
    $zip = Combine $env:TEMP $asset.name
    $unpacked = Combine $env:TEMP ('superspeed-' + [guid]::NewGuid().ToString('N'))
    Invoke-WebRequest -Uri $asset.browser_download_url -OutFile $zip -Headers $headers -UseBasicParsing
    Expand-Archive -LiteralPath $zip -DestinationPath $unpacked -Force
    # Both tools are packaged to go straight into the game folder (bin\..., red4ext\...).
    # If the zip wraps that in one extra folder, step into it.
    $root = (Get-Item -LiteralPath $unpacked).FullName
    $top = @(Get-ChildItem -LiteralPath $root)
    if ($top.Count -eq 1 -and $top[0].PSIsContainer -and @('bin', 'red4ext') -notcontains $top[0].Name) {
        $root = $top[0].FullName
    }
    # Copy file by file so existing folders in the game are merged, not nested.
    foreach ($file in Get-ChildItem -LiteralPath $root -Recurse -File) {
        $relative = $file.FullName.Substring($root.TrimEnd('\').Length + 1)
        $target = Combine $gameDir $relative
        [void][IO.Directory]::CreateDirectory([IO.Path]::GetDirectoryName($target))
        Copy-Item -LiteralPath $file.FullName -Destination $target -Force
    }
    Remove-Item -LiteralPath $zip -Force
    Remove-Item -LiteralPath $unpacked -Recurse -Force
    Say "$label $($release.tag_name) installed." 'Green'
}

function Is-AccessDenied($exception) {
    for ($e = $exception; $e; $e = $e.InnerException) {
        if ($e -is [System.UnauthorizedAccessException]) { return $true }
    }
    return $false
}

try {
    Say ''
    Say '=== Super Speed installer for Cyberpunk 2077 ===' 'Cyan'

    $game = Find-Game
    if (-not $game) { $game = Ask-ForGame }
    if (-not $game) { Say 'Nothing was installed.' 'Yellow'; return }
    Say "Found the game: $game" 'Green'

    while (Get-Process -Name 'Cyberpunk2077' -ErrorAction SilentlyContinue) {
        Say 'Cyberpunk 2077 is running. Close the game, then press Enter.' 'Yellow'
        [void](Read-Host)
    }

    # Modding tools Super Speed depends on.
    $red4extDll = Combine $game 'red4ext\RED4ext.dll'
    $cetAsi = Combine $game 'bin\x64\plugins\cyber_engine_tweaks.asi'
    $needRed4ext = -not (Test-Path -LiteralPath $red4extDll)
    $needCet = -not (Test-Path -LiteralPath $cetAsi)

    if ($needRed4ext -or $needCet) {
        Say ''
        Say 'Super Speed needs these free modding tools, which are not installed yet:' 'Yellow'
        if ($needRed4ext) { Say '  - RED4ext              (github.com/WopsS/RED4ext)' }
        if ($needCet) { Say '  - Cyber Engine Tweaks  (github.com/maximegmd/CyberEngineTweaks)' }
        $yes = Read-Host 'Download and install them now from their official GitHub pages? (Y/N)'
        if ($yes -match '^\s*[Yy]') {
            if ($needRed4ext) { Install-FromGitHub 'WopsS/RED4ext' '^red4ext-[0-9.]+\.zip$' 'RED4ext' $game }
            if ($needCet) { Install-FromGitHub 'maximegmd/CyberEngineTweaks' '^(?!.*(pdb|symbol)).*\.zip$' 'Cyber Engine Tweaks' $game }
            if (-not (Test-Path -LiteralPath $red4extDll) -or -not (Test-Path -LiteralPath $cetAsi)) {
                Say 'A download finished but its files are not where expected. Install it by hand from its GitHub page.' 'Red'
            }
        } else {
            Say 'Skipped. Super Speed will not run until both are installed.' 'Yellow'
        }
    } else {
        Say 'RED4ext and Cyber Engine Tweaks are already installed.' 'Green'
    }

    # The mod itself.
    $modDir = Combine $game 'bin\x64\plugins\cyber_engine_tweaks\mods\SuperSpeed'
    [void][IO.Directory]::CreateDirectory($modDir)
    $initLua = @'
__INIT_LUA__
'@
    [IO.File]::WriteAllText((Combine $modDir 'init.lua'), $initLua, (New-Object System.Text.UTF8Encoding($false)))
    Say "Super Speed installed to $modDir" 'Green'

    Say ''
    Say 'Next:' 'Cyan'
    Say '  1. Start Cyberpunk 2077. The first time, Cyber Engine Tweaks asks you to pick a key for its overlay.'
    Say '  2. Open the overlay, go to Bindings, and set a key for "Toggle super speed" (and/or "Hold for super speed").'
    Say '  3. Load a save and press your key. The Super Speed window with sliders shows while the overlay is open.'
}
catch {
    Say ''
    if (Is-AccessDenied $_.Exception) {
        Say "Windows didn't allow writing to the game folder." 'Red'
        Say 'Right-click this installer and choose "Run as administrator".' 'Red'
    } else {
        Say "Something went wrong: $($_.Exception.Message)" 'Red'
        Say 'The installer stopped here. Send this message to Claude to sort it out.' 'Red'
    }
}
